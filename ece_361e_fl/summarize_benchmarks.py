from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple


PROJECT_DIR = Path(__file__).resolve().parent


def load_json(path: Path) -> Dict:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def parse_config_script(script_path: Path) -> Dict[Tuple[int, int], Dict[str, object]]:
    entries: Dict[Tuple[int, int], Dict[str, object]] = {}
    line_re = re.compile(r'^\s*"([^"]+)"')

    with script_path.open("r", encoding="utf-8") as handle:
        for line in handle:
            match = line_re.match(line)
            if not match:
                continue
            parts = match.group(1).split()
            if len(parts) != 10:
                continue

            exp, run = int(parts[0]), int(parts[1])
            entries[(exp, run)] = {
                "model_name": parts[3],
                "learning_rate": float(parts[4]),
                "loss_type": parts[5],
                "mu": float(parts[6]),
                "beta": float(parts[7]),
                "rpi_local_epochs": int(parts[8]),
                "mc1_local_epochs": int(parts[9]),
                "source": script_path.name,
            }

    return entries


def resolve_job_details(
    exp: int,
    run: int,
    configs_dir: Path,
    script_lookup: Dict[Tuple[int, int], Dict[str, object]],
) -> Dict[str, object]:
    cloud_cfg_path = configs_dir / f"cloud_cfg_exp{exp}_run{run}.json"
    dev_cfg_path = configs_dir / f"dev_cfg_exp{exp}_run{run}.json"

    if cloud_cfg_path.exists() and dev_cfg_path.exists():
        cloud_cfg = load_json(cloud_cfg_path)
        dev_cfg = load_json(dev_cfg_path)
        return {
            "model_name": cloud_cfg.get("model_name"),
            "learning_rate": cloud_cfg.get("learning_rate"),
            "loss_type": cloud_cfg.get("loss_type"),
            "mu": cloud_cfg.get("mu"),
            "beta": cloud_cfg.get("beta"),
            "rpi_local_epochs": dev_cfg.get("dev1", {}).get("local_epochs"),
            "mc1_local_epochs": dev_cfg.get("dev2", {}).get("local_epochs"),
            "source": cloud_cfg_path.name,
        }

    return script_lookup.get((exp, run), {"source": "unknown"})


def format_run(entry: Dict, details: Dict[str, object]) -> str:
    return (
        f"exp{entry['exp']} run{entry['run']} | "
        f"acc={entry.get('global_acc', 0):.2f}% | "
        f"time_to_90={entry.get('time_to_90_s', 0):.2f}s | "
        f"energy={entry.get('total_energy_per_round_j', 0):.2f}J | "
        f"model={details.get('model_name', 'n/a')} | "
        f"loss={details.get('loss_type', 'n/a')} | "
        f"lr={details.get('learning_rate', 'n/a')} | "
        f"mu={details.get('mu', 'n/a')} | "
        f"beta={details.get('beta', 'n/a')} | "
        f"epochs={details.get('rpi_local_epochs', 'n/a')}/{details.get('mc1_local_epochs', 'n/a')}"
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Summarize the best qualifying benchmark runs by time and energy.",
    )
    parser.add_argument(
        "--tracker",
        type=str,
        default="logs/benchmark_tracking.json",
        help="Benchmark tracker JSON generated by cloud_manager.py",
    )
    parser.add_argument("--configs_dir", type=str, default="configs", help="Directory holding generated configs")
    parser.add_argument(
        "--config_scripts",
        nargs="+",
        default=["config_100.bash", "config_m3_pruning.bash"],
        help="Fallback bash scripts used to resolve model/hyperparameter details when config JSON is missing",
    )
    parser.add_argument("--threshold", type=float, default=90.0, help="Minimum global accuracy threshold")
    parser.add_argument("--top_n", type=int, default=5, help="How many qualifying runs to list for each ranking")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    tracker_path = (PROJECT_DIR / args.tracker).resolve()
    configs_dir = (PROJECT_DIR / args.configs_dir).resolve()

    tracker = load_json(tracker_path)
    entries = tracker.get("entries", [])

    qualifying = [
        entry for entry in entries
        if entry.get("qualifies")
        and entry.get("global_acc") is not None
        and float(entry["global_acc"]) >= args.threshold
        and entry.get("time_to_90_s") is not None
        and entry.get("total_energy_per_round_j") is not None
    ]

    if not qualifying:
        print(f"No qualifying runs found at or above {args.threshold:.2f}% accuracy.")
        return

    script_lookup: Dict[Tuple[int, int], Dict[str, object]] = {}
    for script_name in args.config_scripts:
        script_path = (PROJECT_DIR / script_name).resolve()
        if script_path.exists():
            script_lookup.update(parse_config_script(script_path))

    best_time = min(qualifying, key=lambda entry: float(entry["time_to_90_s"]))
    best_energy = min(qualifying, key=lambda entry: float(entry["total_energy_per_round_j"]))
    by_time = sorted(qualifying, key=lambda entry: (float(entry["time_to_90_s"]), float(entry["total_energy_per_round_j"])))
    by_energy = sorted(qualifying, key=lambda entry: (float(entry["total_energy_per_round_j"]), float(entry["time_to_90_s"])))

    best_time_details = resolve_job_details(best_time["exp"], best_time["run"], configs_dir, script_lookup)
    best_energy_details = resolve_job_details(best_energy["exp"], best_energy["run"], configs_dir, script_lookup)

    print(f"Qualifying runs: {len(qualifying)}")
    print(f"Accuracy threshold: {args.threshold:.2f}%")
    print("")
    print("Best wall-clock result:")
    print(f"  {format_run(best_time, best_time_details)}")
    print(f"  detail_source={best_time_details.get('source', 'unknown')}")
    print("")
    print("Best energy result:")
    print(f"  {format_run(best_energy, best_energy_details)}")
    print(f"  detail_source={best_energy_details.get('source', 'unknown')}")
    print("")
    print(f"Top {args.top_n} by time:")
    for entry in by_time[: args.top_n]:
        details = resolve_job_details(entry["exp"], entry["run"], configs_dir, script_lookup)
        print(f"  {format_run(entry, details)}")
    print("")
    print(f"Top {args.top_n} by energy:")
    for entry in by_energy[: args.top_n]:
        details = resolve_job_details(entry["exp"], entry["run"], configs_dir, script_lookup)
        print(f"  {format_run(entry, details)}")


if __name__ == "__main__":
    main()
